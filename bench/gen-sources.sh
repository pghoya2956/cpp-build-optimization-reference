#!/usr/bin/env bash
#
# gen-sources.sh — generate the intentionally-heavy C++ translation units.
#
# The project's whole point is a compile-dominated baseline build, so the heavy
# TUs are synthetic and machine-generated. They are committed to the repo, so a
# plain `git clone && build` works without running this script. Re-run it only
# to re-calibrate: the build is tuned with two knobs ---
#
#   ./bench/gen-sources.sh [TU_COUNT] [GRID_N]
#
# TU_COUNT   number of translation units                       (default 96)
# GRID_N     2D template grid size per TU; cost ~ GRID_N^2      (default 320)
#
# Each TU is kept memory-modest (~0.8 GB peak cc1plus RSS at the defaults) so a
# bounded-parallel baseline build completes without OOM. See heavy_template.hpp.
#
set -euo pipefail

COUNT="${1:-96}"
GRID_N="${2:-320}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CORE="$ROOT/src/core"
INCLUDE="$CORE/include"
LIST="$ROOT/cmake/generated_sources.cmake"
DECL="$INCLUDE/modules.gen.hpp"

rm -f "$CORE"/module_*.cpp
mkdir -p "$CORE" "$INCLUDE"

# --- per-module translation units ------------------------------------------
{
  echo "# AUTO-GENERATED by bench/gen-sources.sh — do not edit by hand."
  echo "# $COUNT translation units, template grid size ~$GRID_N each."
  echo "set(CBOR_GENERATED_SOURCES"
} > "$LIST"

for i in $(seq 0 $((COUNT - 1))); do
  idx="$(printf '%03d' "$i")"
  depth=$((300 + i))
  gridn=$((GRID_N + i % 16))   # slight per-TU variation
  cat > "$CORE/module_${idx}.cpp" <<EOF
// AUTO-GENERATED by bench/gen-sources.sh — intentionally heavy translation unit.
#include "common.hpp"
#include "heavy_template.hpp"

namespace cbor {

double compute_module_${idx}() {
    double acc = Polynomial<${depth}>::eval(0.5);
    acc += static_cast<double>(MetaSum<${depth}ULL>::value % 9973ULL) / 9973.0;
    acc += TypePack<${i}, $((i + 1)), $((i + 2)), $((i + 3))>::fold();
    acc += static_cast<double>(Grid<${gridn}>::value & 0xffffL) / 65535.0;
    acc += mix(acc + ${i}.0);
    acc += regex_score("module ${idx} alpha42 beta tu${i}");
    return acc / 6.0;
}

}  // namespace cbor
EOF
  echo "    src/core/module_${idx}.cpp" >> "$LIST"
done

echo ")" >> "$LIST"

# --- declaration header ------------------------------------------------------
{
  echo "// AUTO-GENERATED by bench/gen-sources.sh — do not edit by hand."
  echo "#pragma once"
  echo "namespace cbor {"
  for i in $(seq 0 $((COUNT - 1))); do
    echo "double compute_module_$(printf '%03d' "$i")();"
  done
  echo
  echo "inline double compute_all_modules() {"
  echo "    double total = 0.0;"
  for i in $(seq 0 $((COUNT - 1))); do
    echo "    total += compute_module_$(printf '%03d' "$i")();"
  done
  echo "    return total;"
  echo "}"
  echo "}  // namespace cbor"
} > "$DECL"

echo "generated $COUNT TUs (template grid ~$GRID_N each)"
echo "  TUs                -> $CORE/module_*.cpp"
echo "  source list        -> $LIST"
echo "  declaration header -> $DECL"
